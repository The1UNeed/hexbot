// Extend the existing exact CPython 3.11 pins for Windows x64. Never resolve
// new versions or trust a locally computed digest without PyPI's metadata.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export function windowsWheel(files) {
  const native = files.filter(file => file.filename.endsWith('-cp311-cp311-win_amd64.whl'))
  const candidates = native.length ? native : files.filter(file => /-py(?:2\.)?3-none-any\.whl$/.test(file.filename))
  assert.equal(candidates.length, 1, 'Expected one Windows CPython 3.11 wheel or universal wheel')
  assert(!candidates[0].yanked, 'Refuse a yanked wheel')
  const url = new URL(candidates[0].url)
  assert(url.protocol === 'https:' && url.hostname === 'files.pythonhosted.org', 'Wheel must come from PyPI storage')
  assert.match(candidates[0].digests.sha256, /^[a-f0-9]{64}$/)
  return candidates[0]
}
export function supportedWheels(files) {
  return files.filter(file => /-py(?:2\.)?3-none-any\.whl$/.test(file.filename) ||
    /-cp311-cp311-(?:macosx_.*_(?:arm64|x86_64|universal2)|manylinux[^-]*_(?:x86_64|aarch64)|musllinux_.*_(?:x86_64|aarch64)|win_amd64)\.whl$/.test(file.filename))
    .sort((a,b) => a.filename.localeCompare(b.filename, 'en'))
}
export function renderLock(pins, records) {
  const expected = [...pins.matchAll(/^([\w-]+)==([^\s]+)/gm)]
  assert.equal(expected.length, records.length)
  return '# Voice tools for managed Python 3.11, installed with --require-hashes --no-deps.\n# Generated by node scripts/desktop/voice-lock.mjs --write from exact .in pins.\n# CPython 3.11 wheels for macOS, Linux and Windows x64.\n' + expected.map(([,name,version],i) => {
    const record = records[i]
    assert(record.name === name && record.version === version, 'Wheel verification differs from locked pins')
    assert(record.hashes.length && record.hashes.includes(record.sha256))
    for (const hash of record.hashes) assert.match(hash, /^[a-f0-9]{64}$/)
    return `${name}==${version} \\\n    ` + [...new Set(record.hashes)].map(hash => `--hash=sha256:${hash}`).join(' \\\n    ')
  }).join('\n') + '\n'
}
// Accept checkout CRLF only. Every pin, digest, ordering and other byte stays
// part of the exact comparison; generated files always use canonical LF.
export function verifyLock(pins, records, text) {
  assert.equal(renderLock(pins, records), text.replaceAll('\r\n', '\n'), 'Voice wheel hashes differ from the generated lock')
}
async function main() {
  const mode = process.argv[2]
  assert(['--check', '--write'].includes(mode) && process.argv.length === 3, 'Use --check or --write')
  const path = new URL('../../backend/hexbot-core/assets/edge-tts.requirements.txt', import.meta.url)
  const audit = new URL('../../backend/hexbot-core/assets/edge-tts.windows-wheels.json', import.meta.url)
  const text = await readFile(path, 'utf8')
  const pins = await readFile(new URL('../../backend/hexbot-core/assets/edge-tts.requirements.in', import.meta.url), 'utf8')
  const records = []
  for (const [, name, version] of pins.matchAll(/^([\w-]+)==([^\s]+)/gm)) {
    const source = `https://pypi.org/pypi/${name}/${version}/json`
    const metadata = await fetch(source); assert(metadata.ok, `PyPI metadata failed: ${name}`)
    const files = (await metadata.json()).urls
    const wheel = windowsWheel(files)
    const verified = await Promise.all(supportedWheels(files).map(async file => {
      assert(!file.yanked && new URL(file.url).protocol === 'https:' && new URL(file.url).hostname === 'files.pythonhosted.org')
      const download = await fetch(file.url); assert(download.ok, `Wheel download failed: ${file.filename}`)
      const bytes = Buffer.from(await download.arrayBuffer())
      assert(bytes.length < 64 * 1024 * 1024, 'Wheel exceeds audit size limit')
      const sha256 = createHash('sha256').update(bytes).digest('hex')
      assert.equal(sha256, file.digests.sha256, `PyPI digest mismatch: ${file.filename}`)
      return sha256
    }))
    records.push({ name, version, filename: wheel.filename, sha256: wheel.digests.sha256, hashes: verified, metadata: source, url: wheel.url })
  }
  const generated = renderLock(pins, records)
  const manifest = JSON.stringify({ python: '3.11', platform: 'win_amd64', wheels: records }, null, 2) + '\n'
  if (mode === '--write') {
    await writeFile(path, generated); await writeFile(audit, manifest)
  } else {
    verifyLock(pins, records, text)
    assert.equal((await readFile(audit, 'utf8')).replaceAll('\r\n', '\n'), manifest, 'Windows wheel audit differs from PyPI')
  }
  console.log(`Verified ${records.length} Windows 3.11 wheels against PyPI metadata and downloaded bytes`)
}
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) await main()
