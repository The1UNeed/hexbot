// Keep mobile's static poses identical to the web's original geometry.
// No browser, animation engine, or third-party datasets are used.
import { readFile, writeFile } from 'node:fs/promises'

const source = new URL('../src/lib/face-geometry.ts', import.meta.url)
const target = new URL('../../mobile/src/ui/face-geometry.ts', import.meta.url)
const generated = '// Generated by apps/web/scripts/face-rest.mjs. Do not edit.\n' + await readFile(source, 'utf8')
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) {
    throw new Error('Mobile face geometry is stale. Run node apps/web/scripts/face-rest.mjs')
  }
} else {
  await writeFile(target, generated)
}
