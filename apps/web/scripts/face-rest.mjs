/**
 * Writes the still faces: where the morph-bot component rests each Hexbot
 * shape's eyes, for the pictures the web app draws (`src/lib/face-rest.ts`)
 * and the faces the mobile app draws (`apps/mobile/src/ui/face-rest.ts`).
 * It runs the component's own eye placement on its own data, so a still
 * face is the live one's first frame.
 *
 *   node apps/web/scripts/face-rest.mjs
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const vendor = join(here, '../src/vendor/morph-bot')
const { EXPRESSIONS, ORIGINAL_STATE_DATA, SHAPES } = await import(join(vendor, 'original-data.js'))
const { renderEyes } = await import(join(vendor, 'runtime/svg-renderer.js'))

/** Hexbot's shapes, by the component shape each one is drawn as. */
const HEXBOT_SHAPES = [
  ['round', 'blob', 'Round'],
  ['squircle', 'squircle', 'Squircle'],
  ['square', 'cylinder', 'Square'],
  ['pill', 'tablet', 'Pill'],
  ['triangle', 'wedge', 'Triangle'],
  ['hexagon', 'hex', 'Hexagon'],
  ['cloud', 'cloud', 'Cloud'],
  ['drop', 'teardrop', 'Drop']
]

/** The moods the mobile app draws; each rests in its state's first expression. */
const MOBILE_MOODS = ['happy', 'idle', 'listening', 'sleeping', 'thinking', 'working']

/** The component's first frame of a state: springs at rest, no drift yet (now = 0). */
function restEyes(shapeId, state) {
  const expression = ORIGINAL_STATE_DATA.EXPRESSION_POOLS[state][0]
  const eyes = [{}, {}].map(() => {
    const attrs = {}

    return { attrs, setAttribute: (name, value) => (attrs[name] = value), style: {} }
  })

  const engine = {
    aimX: { x: 0 },
    aimY: { x: 0 },
    delta: 1 / 60,
    directGazeX: 0,
    directGazeY: 0,
    expressionFrom: EXPRESSIONS[expression],
    expressionSpring: { x: 1 },
    expressionTo: EXPRESSIONS[expression],
    eyeOpen: { x: 1 },
    eyeScale: { x: 1 },
    eyes,
    notify: { x: 0 },
    pointer: { active: false, targetX: 0, targetY: 0, x: 0, y: 0 },
    svg: { getBoundingClientRect: () => ({ height: 100, left: 0, top: 0, width: 100 }) },
    winkAt: Number.NEGATIVE_INFINITY,
    winkEye: -1
  }

  const shape = SHAPES[shapeId]
  renderEyes.call(engine, 0, { flipX: false, pointer: false }, shape, shape.ring, 0, 0)

  return eyes.map(({ attrs }) => {
    const [cx, cy] = attrs.transform.match(/^translate\(([-\d.]+) ([-\d.]+)\)/).slice(1).map(Number)

    return { cx, cy, d: attrs.d, transform: attrs.transform }
  })
}

const header = (command) => `/**
 * Generated by \`node apps/web/scripts/face-rest.mjs\`; do not edit. ${command}
 */
`

const web = {}
const mobileShapes = []
const mobileEyes = {}
const mobilePlaces = {}

for (const [id, shape, label] of HEXBOT_SHAPES) {
  const [left, right] = restEyes(shape, 'idle')
  web[id] = { eyes: [left, right], head: SHAPES[shape].path, label, shape }
  mobileShapes.push({ id, label, path: SHAPES[shape].path })
  mobilePlaces[id] = {}

  for (const mood of MOBILE_MOODS) {
    const eyes = restEyes(shape, mood)
    mobileEyes[mood] = eyes.map((eye) => eye.d)
    mobilePlaces[id][mood] = eyes.map((eye) => eye.transform)
  }
}

const json = (value) => JSON.stringify(value, null, 2).replace(/"([a-z]+)":/g, '$1:').replace(/"/g, "'")

writeFileSync(
  join(here, '../src/lib/face-rest.ts'),
  `${header('The still face of each Hexbot shape: the morph-bot component\'s idle rest, in its head frame.')}
import type { MorphBotShape } from '../vendor/morph-bot/morph-bot.js'

export interface RestEye {
  cx: number
  cy: number
  d: string
  transform: string
}

export interface FaceRest {
  eyes: [RestEye, RestEye]
  /** The head outline in the component's head frame. */
  head: string
  label: string
  /** The component shape the Hexbot shape is drawn as. */
  shape: MorphBotShape
}

export const FACE_REST: Record<string, FaceRest> = ${json(web)}
`
)

writeFileSync(
  join(here, '../../mobile/src/ui/face-rest.ts'),
  `${header('The faces the web app draws, at rest, in the morph-bot head frame.')}
export const FACE_SHAPES: { id: string; label: string; path: string }[] = ${json(mobileShapes)}

/** The eyes a mood rests in, as path data in the head frame; placed per shape by \`EYE_PLACES\`. */
export const EYE_PATHS: Record<string, [string, string]> = ${json(mobileEyes)}

/** The \`transform\` that puts each mood's eyes on each shape. */
export const EYE_PLACES: Record<string, Record<string, [string, string]>> = ${json(mobilePlaces)}
`
)

console.log('wrote face-rest.ts for web and mobile')
